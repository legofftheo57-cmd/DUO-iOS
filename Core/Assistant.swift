import Foundation

/// Local, deterministic guidance. No network call or private data transmission.
/// Suggestions are never applied automatically: the UI requires explicit approval.
public enum AssistantAction: Equatable, Sendable {
    case moveEvent(id: UUID, date: Date)
    case moveTask(id: UUID, date: Date)
    case addShopping(ingredient: Ingredient)
}
public struct AssistantReply: Sendable {
    public let message: String
    public let action: AssistantAction?
    public init(_ message: String, action: AssistantAction? = nil) { self.message = message; self.action = action }
}
public enum InviteLink {
    public static func make(token: String) -> URL? {
        guard valid(token) else { return nil }
        var parts = URLComponents(); parts.scheme = "duo"; parts.host = "invite"
        parts.queryItems = [URLQueryItem(name: "token", value: token)]
        return parts.url
    }
    public static func read(_ url: URL) -> String? {
        guard let parts = URLComponents(url: url, resolvingAgainstBaseURL: false),
              parts.scheme?.lowercased() == "duo", parts.host?.lowercased() == "invite",
              parts.path.isEmpty, parts.user == nil, parts.password == nil,
              let fields = parts.queryItems, fields.count == 1,
              fields[0].name == "token", let token = fields[0].value,
              valid(token) else { return nil }
        return token
    }
    public static func valid(_ token: String) -> Bool {
        // Matches the concatenation of two canonical UUIDs generated by invite_partner().
        guard token.count == 72 else { return false }
        let pieces = [String(token.prefix(36)), String(token.suffix(36))]
        return pieces.allSatisfy { UUID(uuidString: $0) != nil }
    }
}

public enum DuoAssistant {
    public static func answer(_ question: String, records: [Record], recipes: [Recipe], stock: [Food], exclusions: Set<String>, now: Date = Date(), calendar: Calendar = .current) -> AssistantReply {
        let q = normalized(question)
        guard !q.isEmpty, question.count <= 800 else { return AssistantReply("Écris une question courte (800 caractères maximum).") }
        // Joe can draft a grocery-list change; this is never persisted in the core.
        // Only clear shopping commands are accepted; other questions stay read-only.
        if let item = groceryRequest(q) {
            return AssistantReply("Je propose d’ajouter « \(item.name) » (\(item.quantity.formatted()) \(item.unit.label)) à la liste de courses. Rien ne sera ajouté sans confirmation.", action: .addShopping(ingredient: item))
        }
        let wantsMove = ["decale", "decaler", "deplace", "deplacer", "reporte", "reporter", "repousser", "repousse"].contains { q.contains($0) }
        if wantsMove {
            guard q.contains("demain") else { return AssistantReply("Je peux préparer le déplacement d’un événement ou d’une tâche à demain. Précise son nom, par exemple : « Décale le sport à demain ». Tu confirmeras avant tout changement.") }
            let subject = extractSubject(q)
            guard !subject.isEmpty else { return AssistantReply("Précise le nom de l’événement ou de la tâche à déplacer.") }
            let possible = records.filter { row in
                guard !row.deleted else { return false }
                let name: String
                switch row.payload { case .event(let e): name = e.title; case .task(let t): name = t.title; default: return false }
                let title = normalized(name)
                return title == subject || title.contains(subject) || subject.contains(title)
            }
            guard possible.count == 1, let row = possible.first else {
                return AssistantReply(possible.isEmpty ? "Je n’ai pas trouvé cette tâche ou cet événement. Vérifie son nom dans le planning." : "Plusieurs éléments correspondent. Indique un nom plus précis pour éviter de modifier le mauvais.")
            }
            guard let day = calendar.date(byAdding: .day, value: 1, to: calendar.startOfDay(for: now)) else { return AssistantReply("Je n’ai pas pu calculer la date.") }
            switch row.payload {
            case .event(let event):
                let time = calendar.dateComponents([.hour, .minute, .second], from: event.start)
                guard let target = calendar.date(bySettingHour: time.hour ?? 0, minute: time.minute ?? 0, second: time.second ?? 0, of: day) else { return AssistantReply("Impossible de conserver cet horaire à cette date.") }
                let overlaps = records.contains { other in
                    guard other.id != row.id, !other.deleted, case .event(let e) = other.payload else { return false }
                    return target < e.end && target.addingTimeInterval(event.end.timeIntervalSince(event.start)) > e.start
                }
                let warning = overlaps ? " Attention : un autre événement chevauche ce nouvel horaire." : ""
                return AssistantReply("Je propose de déplacer « \(event.title) » à demain, \(target.formatted(date: .abbreviated, time: .shortened)), en conservant sa durée.\(warning) Confirme avant d’appliquer.", action: .moveEvent(id: row.id, date: target))
            case .task(let task):
                let original = task.due ?? now
                let time = calendar.dateComponents([.hour, .minute], from: original)
                guard let target = calendar.date(bySettingHour: time.hour ?? 18, minute: time.minute ?? 0, second: 0, of: day) else { return AssistantReply("Impossible de calculer cet horaire.") }
                return AssistantReply("Je propose de déplacer « \(task.title) » à demain à \(target.formatted(date: .omitted, time: .shortened)). Confirme avant d’appliquer.", action: .moveTask(id: row.id, date: target))
            default: break
            }
        }
        if ["recette", "manger", "cuisiner", "repas", "diner", "dejeuner", "frigo", "ingredient"].contains(where: q.contains) {
            // Use the existing recipe engine to honour known exclusions and stock.
            let proposals = MealEngine.suggestions(catalog: recipes, stock: stock, exclusions: exclusions, recent: []).prefix(3)
            guard !proposals.isEmpty else { return AssistantReply("Aucune recette du catalogue ne correspond à tes exclusions. Vérifie les exclusions dans les réglages.") }
            let entries = proposals.map { recipe -> String in
                let missing = MealEngine.missing(recipe.ingredients, stock: stock, now: now)
                let detail = missing.isEmpty ? "tout est disponible" : "à prévoir : " + missing.prefix(4).map(\.name).joined(separator: ", ")
                return "• \(recipe.title) (\(recipe.preparation + recipe.cooking) min) — \(detail)"
            }
            return AssistantReply("Voici des idées tirées des recettes incluses dans DUO :\n" + entries.joined(separator: "\n") + "\nVérifiez toujours les ingrédients et allergènes si nécessaire.")
        }
        if ["marque", "acheter", "magasin", "prix", "moins cher", "compar"].contains(where: q.contains) {
            return AssistantReply("Je peux t’aider à choisir selon ton budget, le prix au kilo/litre, la composition et la durée de conservation. Indique le produit et ton budget. En mode local, je ne connais ni les prix actuels des magasins ni leurs stocks : je ne vais pas inventer une marque « moins chère ».")
        }
        if ["planning", "programme", "aujourd", "semaine", "quoi faire"].contains(where: q.contains) {
            let upcoming = records.compactMap { row -> (Date,String)? in
                guard !row.deleted else { return nil }
                switch row.payload { case .event(let e) where e.end >= now: return (e.start,e.title)
                case .task(let t) where t.completed == nil && t.due != nil && t.due! >= now: return (t.due!,t.title)
                default: return nil }
            }.sorted { $0.0 < $1.0 }.prefix(4)
            if upcoming.isEmpty { return AssistantReply("Aucun événement ou tâche datée à venir dans les données présentes sur cet iPhone.") }
            return AssistantReply("Voici les prochaines échéances :\n" + upcoming.map { "• \($0.1) — \($0.0.formatted(date: .abbreviated, time: .shortened))" }.joined(separator: "\n"))
        }
        return AssistantReply("Je peux proposer des recettes à partir de votre stock, résumer votre planning et préparer un déplacement à demain. Pour des questions plus libres, le mode conversationnel pourra être activé séparément lorsque le service IA sécurisé sera configuré.")
    }
    // Recognizes simple French requests without inventing products, prices or quantities.
    // E.g. "Ajoute 2 kg de riz aux courses" or "Mets du lait sur la liste de courses".
    private static func groceryRequest(_ q: String) -> Ingredient? {
        guard q.contains("course") || q.contains("liste") else { return nil }
        let begins = ["ajoute ", "ajouter ", "mets ", "mettre ", "note ", "noter "]
        guard let prefix = begins.first(where: { q.hasPrefix($0) }) else { return nil }
        var product = String(q.dropFirst(prefix.count))
        let ends = [" sur la liste de courses", " a la liste de courses", " dans la liste de courses", " dans les courses", " aux courses", " sur la liste", " dans la liste", " a la liste"]
        guard let suffix = ends.first(where: { product.hasSuffix($0) }) else { return nil }
        product.removeLast(suffix.count)
        product = product.trimmingCharacters(in: .whitespacesAndNewlines.union(.punctuationCharacters))
        for article in ["de la ", "des ", "du ", "de l'", "de ", "d'", "un ", "une ", "le ", "la ", "les ", "l'"] where product.hasPrefix(article) {
            product.removeFirst(article.count)
            break
        }
        var quantity = 1.0
        var unit: FoodUnit = .piece
        let words = product.split(separator: " ").map(String.init)
        if let first = words.first, let number = Double(first.replacingOccurrences(of: ",", with: ".")) {
            guard number > 0, number <= 100_000, number.isFinite else { return nil }
            quantity = number
            var remainder = Array(words.dropFirst())
            if let firstUnit = remainder.first {
                switch firstUnit {
                case "kg", "g", "l", "ml":
                    unit = FoodUnit(rawValue: firstUnit)!
                    remainder.removeFirst()
                case "pieces", "piece":
                    unit = .piece
                    remainder.removeFirst()
                default: break
                }
            }
            if let article = remainder.first, ["de", "du", "des", "la", "le", "d'"].contains(article) { remainder.removeFirst() }
            product = remainder.joined(separator: " ")
        }
        product = product.trimmingCharacters(in: .whitespacesAndNewlines.union(.punctuationCharacters))
        guard !product.isEmpty, product.count <= 100,
              product.unicodeScalars.allSatisfy({ !CharacterSet.controlCharacters.contains($0) }),
              unit != .piece || quantity.rounded() == quantity else { return nil }
        return Ingredient(product, quantity, unit)
    }
    private static func extractSubject(_ q: String) -> String {
        var result = q
        for verb in ["decaler", "decale", "deplacer", "deplace", "reporter", "reporte", "repousser", "repousse"] {
            if let range = result.range(of: verb) { result = String(result[range.upperBound...]); break }
        }
        if let range = result.range(of: "demain") { result = String(result[..<range.lowerBound]) }
        result = result.trimmingCharacters(in: .whitespacesAndNewlines)
        for prefix in ["le ", "la ", "les ", "l'", "mon ", "ma ", "notre ", "un ", "une "] where result.hasPrefix(prefix) { result.removeFirst(prefix.count); break }
        // Remove a trailing preposition only as a complete word, never the last
        // letter of a title such as "Yoga" or "Pasta".
        for suffix in [" a", " au", " pour"] where result.hasSuffix(suffix) {
            result.removeLast(suffix.count)
            break
        }
        return result.trimmingCharacters(in: .whitespacesAndNewlines.union(.punctuationCharacters))
    }
}
